package com.bugsy.core.model

import kotlinx.serialization.Serializable

/**
 * An interception rule: requests whose method and URL match [urlPattern] get [statusCode]/[responseHeaders]/
 * [responseBody] instead of hitting the network. `null` [method] matches any method ("ANY" in the UI).
 *
 * @param name optional label shown instead of [urlPattern] in the UI (e.g. "Login 401" instead of
 * "^/api/v1/auth/login$"); blank or `null` falls back to the pattern.
 * @param hitCount how many times this rule has fired, shown in its detail screen; `0` for a never-fired or
 * freshly created rule, reset when the rule is edited and saved again.
 */
@Serializable
data class MockRule(
    val id: String,
    val urlPattern: String,
    val name: String? = null,
    val method: String? = null,
    val statusCode: Int = 200,
    val responseHeaders: Map<String, String> = mapOf("Content-Type" to "application/json"),
    val responseBody: String = "",
    val delayMs: Long = 0,
    val isOneShot: Boolean = false,
    val isActive: Boolean = true,
    val hitCount: Int = 0,
)

/**
 * [MockRule.name] when set and non-blank, [MockRule.urlPattern] otherwise — what the UI shows as the rule's label.
 * The pattern fallback drops the `^`/`$` anchors and unescapes backslash-escaped regex metacharacters, so a
 * pattern like `^/v1/files/report\.pdf$` (as generated by "Create mock from this response") reads as the plain
 * route `/v1/files/report.pdf` instead of leaking its regex syntax.
 */
val MockRule.displayName: String
    get() = name?.takeIf { it.isNotBlank() } ?: urlPattern.toDisplayRoute()

/** [MockRule.urlPattern] cleaned up the same way as the [displayName] fallback, for showing it as a secondary caption alongside a custom [MockRule.name] (e.g. under "Login failure"). */
val MockRule.displayPattern: String
    get() = urlPattern.toDisplayRoute()

private fun String.toDisplayRoute(): String {
    val withoutAnchors = removePrefix("^").removeSuffix("$")
    return buildString {
        var i = 0
        while (i < withoutAnchors.length) {
            val c = withoutAnchors[i]
            if (c == '\\' && i + 1 < withoutAnchors.length && withoutAnchors[i + 1] in "\\^$.|?*+()[]{}") {
                append(withoutAnchors[i + 1])
                i += 2
            } else {
                append(c)
                i += 1
            }
        }
    }
}

/** One time [MockRule] fired: the exact URL it matched and when, shown in the rule's "Last matches" list. */
data class MockMatch(
    val url: String,
    val timestamp: Long,
)
